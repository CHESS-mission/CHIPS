#!/usr/bin/env python3

import sys

POLYNOMIAL = 0x8408
MAX_FOLD = 16
VALUES_PER_LINE = 8
OUTPUT = "crc16_kermit_tables.h"

def build_base_table():
    table = []
    for byte in range(256):
        crc = byte
        for _ in range(8):
            crc = (crc >> 1) ^ POLYNOMIAL if crc & 1 else crc >> 1
        table.append(crc)
    return table


def build_tables(fold):
    tables = [build_base_table()]
    for _ in range(1, fold):
        previous = tables[-1]
        tables.append([(v >> 8) ^ tables[0][v & 0xFF] for v in previous])
    return tables


def format_table(table, indent):
    lines = []
    for start in range(0, 256, VALUES_PER_LINE):
        chunk = table[start:start + VALUES_PER_LINE]
        lines.append(indent + ", ".join(f"0x{v:04X}u" for v in chunk) + ",")
    return "\n".join(lines)


def render(tables):
    out = []
    out.append("/* Generated by gen_crc16_kermit_tables.py. Do not edit. */")
    out.append("#ifndef CHIPS_CRC16_KERMIT_TABLES_H")
    out.append("#define CHIPS_CRC16_KERMIT_TABLES_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append(f"#define CHIPS_CRC16_KERMIT_FOLD_MAX {len(tables)}")
    out.append("")
    out.append("#ifndef CHIPS_CRC16_KERMIT_FOLD")
    out.append("#error \"CHIPS_CRC16_KERMIT_FOLD must be defined\"")
    out.append("#endif")
    out.append("#if CHIPS_CRC16_KERMIT_FOLD < 1")
    out.append("#error \"CHIPS_CRC16_KERMIT_FOLD must be at least 1\"")
    out.append("#endif")
    out.append("#if CHIPS_CRC16_KERMIT_FOLD > CHIPS_CRC16_KERMIT_FOLD_MAX")
    out.append("#error \"CHIPS_CRC16_KERMIT_FOLD exceeds CHIPS_CRC16_KERMIT_FOLD_MAX; "
               "raise MAX_FOLD in gen_crc16_kermit_tables.py and regenerate\"")
    out.append("#endif")
    out.append("")
    out.append("static const uint16_t crc16_kermit_table[CHIPS_CRC16_KERMIT_FOLD][256] = {")
    for slice_index, table in enumerate(tables):
        if slice_index > 0:
            out.append(f"#if CHIPS_CRC16_KERMIT_FOLD > {slice_index}")
        out.append(f"    {{ /* slice {slice_index} */")
        out.append(format_table(table, "        "))
        out.append("    },")
        if slice_index > 0:
            out.append("#endif")
    out.append("};")
    out.append("")
    out.append("#endif /* CHIPS_CRC16_KERMIT_TABLES_H */")
    out.append("")
    return "\n".join(out)


def main():
    with open(OUTPUT, "w", newline="\n") as f:
        f.write(render(build_tables(MAX_FOLD)))
    return 0

if __name__ == "__main__":
    sys.exit(main())
